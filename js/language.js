const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const languageSelect = document.querySelector('#language-select');
const languageStorageKey = 'developerhcr-language';
const originalPageTitle = document.title;

function translated(value, language) {
  const phrase = value.trim();
  const translation = translations[language]?.[phrase];
  if (!translation) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translation}${trailing}`;
}

function applyLanguage(language) {
  const selectedLanguage = translations[language] ? language : 'en';
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;

  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    node.nodeValue = translated(originalText.get(node), selectedLanguage);
  }

  document.querySelectorAll('[placeholder], [aria-label], [title]').forEach((element) => {
    if (!originalAttributes.has(element)) {
      originalAttributes.set(element, {
        placeholder: element.getAttribute('placeholder'),
        ariaLabel: element.getAttribute('aria-label'),
        title: element.getAttribute('title')
      });
    }

    const original = originalAttributes.get(element);
    for (const [attribute, key] of [
      ['placeholder', 'placeholder'],
      ['aria-label', 'ariaLabel'],
      ['title', 'title']
    ]) {
      if (original[key] !== null) {
        element.setAttribute(attribute, translated(original[key], selectedLanguage));
      }
    }
  });

  const titles = {
    'Contact | DeveloperHCR': {
      hi: 'संपर्क | DeveloperHCR',
      hinglish: 'Contact | DeveloperHCR'
    },
    'About DeveloperHCR': {
      hi: 'DeveloperHCR परिचय',
      hinglish: 'About DeveloperHCR'
    },
    'Projects | DeveloperHCR': {
      hi: 'प्रोजेक्ट | DeveloperHCR',
      hinglish: 'Projects | DeveloperHCR'
    },
    'AI & API | DeveloperHCR': {
      hi: 'एआई और एपीआई | DeveloperHCR',
      hinglish: 'AI & API | DeveloperHCR'
    },
    'Services | DeveloperHCR': {
      hi: 'सेवाएँ | DeveloperHCR',
      hinglish: 'Services | DeveloperHCR'
    },
    'Downloads | DeveloperHCR': {
      hi: 'डाउनलोड | DeveloperHCR',
      hinglish: 'Downloads | DeveloperHCR'
    },
    'Documentation | DeveloperHCR': {
      hi: 'दस्तावेज़ | DeveloperHCR',
      hinglish: 'Documentation | DeveloperHCR'
    },
    'Gallery | DeveloperHCR': {
      hi: 'गैलरी | DeveloperHCR',
      hinglish: 'Gallery | DeveloperHCR'
    },
    'Privacy Policy | DeveloperHCR': {
      hi: 'गोपनीयता नीति | DeveloperHCR',
      hinglish: 'Privacy policy | DeveloperHCR'
    },
    'Terms & Conditions | DeveloperHCR': {
      hi: 'नियम और शर्तें | DeveloperHCR',
      hinglish: 'Terms aur conditions | DeveloperHCR'
    },
    'DeveloperHCR — Software & Technology': {
      hi: 'DeveloperHCR — सॉफ्टवेयर और टेक्नोलॉजी',
      hinglish: 'DeveloperHCR — Software aur Technology'
    }
  };
  document.title = selectedLanguage === 'en'
    ? originalPageTitle
    : titles[originalPageTitle]?.[selectedLanguage] ?? originalPageTitle;
  document.documentElement.lang = selectedLanguage === 'hi' ? 'hi' : 'en-IN';
  if (languageSelect) languageSelect.value = selectedLanguage;
}

if (languageSelect) {
  const savedLanguage = localStorage.getItem(languageStorageKey) || 'en';
  applyLanguage(savedLanguage);
  languageSelect.addEventListener('change', () => {
    localStorage.setItem(languageStorageKey, languageSelect.value);
    applyLanguage(languageSelect.value);
  });
}
